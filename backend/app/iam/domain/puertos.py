    def por_id(self, usuario_id: uuid.UUID) -> Usuario | None: ...
    def por_email(self, email: str) -> Usuario | None: ...
    def listar(self) -> list[Usuario]: ...
    def guardar(self, usuario: Usuario) -> None: ...
    def hay_admin(self) -> bool: ...


